#!/usr/bin/env python3
"""Technical bootstrap configuration; business and SMTP setup are handled in the browser."""
import datetime
import getpass
import os
from pathlib import Path
import re
import secrets
import sys
import tempfile
from urllib.parse import quote, urlsplit


def read_env(path):
    values = {}
    if not path.exists():
        return values
    for line in path.read_text().splitlines():
        match = re.match(r'^([A-Z][A-Z0-9_]*)=(.*)$', line.strip())
        if not match:
            continue
        name, value = match.groups()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[name] = value
    return values


def encode_env(value):
    if "'" in value or any(c in value for c in '\r\n\x00'):
        raise ValueError('Nilai konfigurasi tidak boleh mengandung apostrof atau baris baru')
    return "'" + value + "'"


def write_env(path, values):
    # Compose single-quoted values are literal, including dollars in credentials.
    content = '# Generated by scripts/setup-env.py\n' + ''.join(
        f'{key}={encode_env(str(value))}\n' for key, value in values.items()
    )
    if path.is_symlink():
        raise ValueError('.env berupa symlink. Periksa targetnya dahulu.')
    if path.exists():
        stamp = datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f')
        backup = path.with_name(f'.env.backup.{stamp}')
        fd = os.open(backup, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, 'wb') as handle:
            handle.write(path.read_bytes())
        print('Konfigurasi sebelumnya sudah dibackup.')
    fd, temporary = tempfile.mkstemp(prefix='.env.setup.', dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def ask(label, default='', validate=None):
    while True:
        value = input(f'{label}' + (f' [{default}]' if default else '') + ': ').strip() or default
        if not value:
            print('Wajib diisi.')
            continue
        try:
            encode_env(value)
            if validate and not validate(value):
                raise ValueError('Format tidak valid. Coba lagi.')
            return value
        except ValueError as error:
            print(error)


def valid_email(value):
    return bool(re.fullmatch(r'[^\s@]+@[^\s@]+\.[^\s@]+', value))


def valid_url(value):
    url = urlsplit(value)
    return (url.scheme == 'https' and bool(url.hostname) and url.path in ('', '/')
            and not url.query and not url.fragment and not url.username and not url.password)


def main():
    path = Path('.env')
    values = read_env(Path('.env.example'))
    previous = read_env(path)
    old_key = previous.get('SESSION_ENCRYPTION_KEY', '')
    if old_key and not re.fullmatch(r'[a-fA-F0-9]{64}', old_key):
        raise ValueError('Kunci enkripsi lama tidak valid. Pulihkan kunci lama sebelum melanjutkan; file belum diubah.')
    if not old_key and (Path('data/app.sqlite').exists() or os.environ.get('WABLASTING_EXISTING_VOLUME') == '1'):
        raise ValueError('Database/volume lama terdeteksi tetapi kunci .env hilang. Pulihkan SESSION_ENCRYPTION_KEY dari backup; data tidak dihapus.')
    values.update(previous)
    print('\nSETUP WABLASTING — isi pertanyaan berikut, tanpa nano.\n')
    values['APP_URL'] = ask('URL aplikasi', previous.get('APP_URL', '') if valid_url(previous.get('APP_URL', '')) else 'https://whapi.avicennarabama.com', valid_url).rstrip('/')
    values['BUSINESS_NAME'] = ask('Nama bisnis/pengelola', previous.get('BUSINESS_NAME', ''))
    values['ADMIN_EMAILS'] = ask('Email login admin', previous.get('ADMIN_EMAILS', '').split(',')[0], valid_email).lower()
    values['SUPPORT_EMAIL'] = ask('Email bantuan pelanggan', previous.get('SUPPORT_EMAIL') or values['ADMIN_EMAILS'], valid_email)
    old_smtp = previous.get('SMTP_URL', '')
    keep_smtp = False
    if old_smtp and urlsplit(old_smtp).scheme in ('smtp', 'smtps'):
        keep_smtp = input('Konfigurasi SMTP lama ditemukan. Pertahankan? [Y/n]: ').strip().lower() != 'n'
    if not keep_smtp:
        print('\nGunakan detail SMTP dari penyedia email kamu.')
        host = ask('Host SMTP (contoh smtp.gmail.com)', validate=lambda v: bool(re.fullmatch(r'[a-zA-Z0-9.-]+', v)))
        port = ask('Port SMTP', '587', lambda v: v.isdigit() and 1 <= int(v) <= 65535)
        user = ask('Username SMTP')
        secret = ''
        while not secret:
            secret = getpass.getpass('Password SMTP / App Password (ketikan tidak terlihat): ')
        scheme = 'smtps' if port == '465' else 'smtp'
        values['SMTP_URL'] = f'{scheme}://{quote(user, safe="")}:{quote(secret, safe="")}@{host}:{port}'
    values['MAIL_FROM'] = ask('Email pengirim yang diizinkan SMTP', previous.get('MAIL_FROM') or values['ADMIN_EMAILS'], valid_email)
    values['PAYMENT_INSTRUCTIONS'] = ask('Instruksi transfer (bank, nomor rekening, nama penerima)', previous.get('PAYMENT_INSTRUCTIONS', ''))
    values.update(NODE_ENV='production', COOKIE_SECURE='true', HOST='127.0.0.1', PORT='3000')
    values['SESSION_ENCRYPTION_KEY'] = old_key or secrets.token_hex(32)
    write_env(path, values)
    print('\n.env berhasil disimpan otomatis. Rahasia tidak ditampilkan.')


def minimal():
    path = Path('.env')
    previous = read_env(path)
    values = read_env(Path('.env.example'))
    values.update(previous)
    key = previous.get('SESSION_ENCRYPTION_KEY', '')
    if key and not re.fullmatch(r'[a-fA-F0-9]{64}', key):
        raise ValueError('Kunci enkripsi lama tidak valid. Pulihkan kunci dari backup.')
    if not key and (Path('data/app.sqlite').exists() or os.environ.get('WABLASTING_EXISTING_VOLUME') == '1'):
        raise ValueError('Database/volume lama ada tetapi kunci hilang. Pulihkan SESSION_ENCRYPTION_KEY dari backup; database tidak dihapus.')
    domain = os.environ.get('WABLASTING_DOMAIN') or previous.get('APP_URL') or 'https://whapi.avicennarabama.com'
    if not domain.startswith(('http://', 'https://')):
        domain = 'https://' + domain
    if not valid_url(domain):
        raise ValueError('URL produksi harus HTTPS dan tanpa path.')
    values.update(APP_URL=domain.rstrip('/'), NODE_ENV='production', COOKIE_SECURE='true', HOST='127.0.0.1', PORT='3000', SESSION_ENCRYPTION_KEY=key or secrets.token_hex(32))
    write_env(path, values)
    print('Konfigurasi teknis tersimpan. Buat akun admin dan atur layanan melalui browser.')


if __name__ == '__main__':
    # A pasted heredoc uses stdin for script text; all prompts read the terminal.
    try:
        if '--interactive' in sys.argv:
            with open('/dev/tty') as terminal:
                sys.stdin = terminal
                main()
        else:
            minimal()
    except (ValueError, OSError, KeyboardInterrupt) as error:
        print(f'\nSetup berhenti: {error}', file=sys.stderr)
        sys.exit(1)
